import fs from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const pluginRequire = createRequire(require.resolve('@tailwindcss/postcss'));
const postcss = pluginRequire('postcss');
const tailwind = require('@tailwindcss/postcss');

const cssPath = fileURLToPath(new URL('../app/globals.css', import.meta.url));
const outputPath = fileURLToPath(new URL('../app/styles.generated.ts', import.meta.url));

const source = await fs.readFile(cssPath, 'utf8');
const result = await postcss([tailwind()]).process(source, { from: cssPath });
await fs.writeFile(outputPath, '// Generated by scripts/inline-styles.mjs. Edit globals.css instead.\nexport const criticalStyles = ' + JSON.stringify(result.css) + ';\n');
console.log('Embedded styles generated.');

